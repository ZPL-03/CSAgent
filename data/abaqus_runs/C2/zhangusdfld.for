      SUBROUTINE USDFLD(FIELD,STATEV,PNEWDT,DIRECT,T,CELENT,TIME,DTIME,
     1 CMNAME,ORNAME,NFIELD,NSTATV,NOEL,NPT,LAYER,KSPT,KSTEP,KINC,
     2 NDI,NSHR,COORD,JMAC,JMTYP,MATLAYO,LACCFLG)
      INCLUDE 'ABA_PARAM.INC'
C     材料强度由当前候选输入生成，单位为 MPa。
      INCLUDE 'pressure_hull_strength.inc'
      CHARACTER*80 CMNAME,ORNAME
      CHARACTER*3 FLGRAY(15)
      DIMENSION FIELD(NFIELD),STATEV(NSTATV),DIRECT(3,3),T(3,3),
     1 TIME(2),ARRAY(15),JARRAY(15),COORD(*),JMAC(*),JMTYP(*)
C     三个不可逆标记分别控制横向、剪切和纤维刚度退化。
      CR11=STATEV(1)
      CR22=STATEV(2)
      CR33=STATEV(3)
      CALL GETVRM('S',ARRAY,JARRAY,FLGRAY,JRCD,
     1 JMAC,JMTYP,MATLAYO,LACCFLG)
      ST11=ARRAY(1)
      ST22=ARRAY(2)
      ST12=ARRAY(4)
      CR1=(ST11/XC)**2
      CR2=(ST11/XT)**2
      CR3=(ST22/YC)**2+(ST12/S12)**2
      CR4=(ST22/YT)**2+(ST12/S12)**2
      CR5=(ST11/XC)**2+(ST12/S12)**2
      IF (ST22.LE.0.D0) THEN
          IF (CR3.GE.1.D0) CR11=1.D0
      ELSE
          IF (CR4.GE.1.D0) CR11=1.D0
      ENDIF
      IF (ST11.LE.0.D0) THEN
          IF (CR1.GE.1.D0) CR33=1.D0
          IF (CR5.GE.1.D0) CR22=1.D0
      ELSE
          IF (CR2.GE.1.D0) CR33=1.D0
      ENDIF
      STATEV(1)=CR11
      STATEV(2)=CR22
      STATEV(3)=CR33
      FIELD(1)=CR11
      FIELD(2)=CR22
      FIELD(3)=CR33
      RETURN
      END
